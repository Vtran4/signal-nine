# embed_assets.py — makes the game playable from file:// double-click.
# Signal Nine version: auto-discovers baked atlases instead of a hardcoded table,
# so modeler-s9 can add atlas groups with zero renames and zero edits here.
#   1) re-encodes assets/albedo_*.png -> .jpg (q90, sRGB) and light_*.png -> .jpg (q88, linear)
#   2) copies *.glb and manifest.json as-is
#   3) writes assets/manifest.js (window.__S9_MANIFEST) and
#      assets/assets_embed.js (window.__S9_ASSETS, base64 data URIs) —
#      index.html loads them as classic scripts; no fetch, no CORS, works on file://.
# manifest.json itself is EMITTED by blender/bake.py (group prefix -> atlas); we only read it.
# Run:  python tools/embed_assets.py
import base64, glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
ASSETS = os.path.join(ROOT, "assets")

try:
    from PIL import Image
except ImportError:
    print("Pillow is required: pip install pillow")
    sys.exit(1)

JPG_ALBEDO_Q = 90   # painted albedo survives JPEG fine
JPG_LIGHT_Q = 88    # lightmaps are linear data; sampled as NoColorSpace either way


def main():
    jpgs = []   # (png_path, jpg_name, quality)
    for png in sorted(glob.glob(os.path.join(ASSETS, "albedo_*.png"))):
        jpgs.append((png, os.path.basename(png)[:-4] + ".jpg", JPG_ALBEDO_Q))
    for png in sorted(glob.glob(os.path.join(ASSETS, "light_*.png"))):
        jpgs.append((png, os.path.basename(png)[:-4] + ".jpg", JPG_LIGHT_Q))

    # 1) re-encode atlases png -> jpg
    for png, name, q in jpgs:
        jpg = os.path.join(ASSETS, name)
        if os.path.exists(jpg) and os.path.getmtime(jpg) >= os.path.getmtime(png):
            continue  # fresh already
        img = Image.open(png)
        img.convert("RGB").save(jpg, "JPEG", quality=q, optimize=True)
        print(f"{name}: {os.path.getsize(png)//1024} KB -> {os.path.getsize(jpg)//1024} KB")
    if not jpgs:
        print("no atlases yet (albedo_*/light_* pngs) — glb-only pass")

    # 2) manifest.js — bake.py writes manifest.json; we wrap it for file://
    mani_path = os.path.join(ASSETS, "manifest.json")
    if os.path.exists(mani_path):
        with open(mani_path, "r") as f:
            mani = f.read()
        with open(os.path.join(ASSETS, "manifest.js"), "w") as f:
            f.write("// generated by tools/embed_assets.py — inline manifest for file:// play\n")
            f.write("window.__S9_MANIFEST = " + mani + ";\n")
        print("manifest.js written")
    else:
        print("no manifest.json yet (bake.py emits it)")

    # 3) assets_embed.js — base64 bundle of everything
    names = [n for _, n, _ in jpgs]
    for glb in sorted(glob.glob(os.path.join(ASSETS, "*.glb"))):
        names.append(os.path.basename(glb))
    names.append("manifest.json")

    out = ["// generated by tools/embed_assets.py — base64 asset bundle for file:// play",
           "window.__S9_ASSETS = window.__S9_ASSETS || {};"]
    total = 0
    for name in sorted(set(names)):
        path = os.path.join(ASSETS, name)
        if not os.path.exists(path):
            print("MISSING:", name)
            continue
        with open(path, "rb") as f:
            data = f.read()
        total += len(data)
        mime = ("image/jpeg" if name.endswith(".jpg")
                else "image/png" if name.endswith(".png")
                else "model/gltf-binary" if name.endswith(".glb")
                else "application/json")
        b64 = base64.b64encode(data).decode("ascii")
        out.append(f'window.__S9_ASSETS["{name}"] = "data:{mime};base64,{b64}";')
    with open(os.path.join(ASSETS, "assets_embed.js"), "w") as f:
        f.write("\n".join(out) + "\n")
    if total:
        print(f"assets_embed.js: {total//1024} KB raw -> {os.path.getsize(os.path.join(ASSETS, 'assets_embed.js'))//1024} KB encoded")
    else:
        print("assets_embed.js: empty (greybox phase — expected)")


if __name__ == "__main__":
    main()